/**
 * Generates a fresh deployer keypair.
 *
 *  - Private key  -> contracts/bsc/.env  (DEPLOYER_PRIVATE_KEY, file is gitignored)
 *  - Address only -> contracts/bsc/deployments/deployer.txt
 *
 * Refuses to overwrite an existing DEPLOYER_PRIVATE_KEY unless --force is passed.
 *
 *   npm run new-deployer
 *   npm run new-deployer -- --force
 */
import { Wallet } from "ethers";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(__dirname, "..");
const envPath = join(root, ".env");
const deploymentsDir = join(root, "deployments");
const force = process.argv.includes("--force");

function main() {
  let env = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
  const existing = env.match(/^DEPLOYER_PRIVATE_KEY=(0x[0-9a-fA-F]{64})\s*$/m);
  if (existing && !force) {
    const addr = new Wallet(existing[1]).address;
    console.log(`[new-deployer] .env already has DEPLOYER_PRIVATE_KEY for ${addr}. Use --force to replace it.`);
    writeDeployerTxt(addr);
    return;
  }

  const wallet = Wallet.createRandom();
  const line = `DEPLOYER_PRIVATE_KEY=${wallet.privateKey}`;
  if (/^DEPLOYER_PRIVATE_KEY=.*$/m.test(env)) {
    env = env.replace(/^DEPLOYER_PRIVATE_KEY=.*$/m, line);
  } else {
    if (env.length && !env.endsWith("\n")) env += "\n";
    env += `# Generated by scripts/new-deployer.ts on ${new Date().toISOString()} — address ${wallet.address}\n${line}\n`;
  }
  writeFileSync(envPath, env, { encoding: "utf8" });
  writeDeployerTxt(wallet.address);
  console.log(`[new-deployer] deployer address: ${wallet.address}`);
  console.log(`[new-deployer] private key written to ${envPath} (gitignored). Fund this address with BNB before deploying.`);
}

function writeDeployerTxt(address: string) {
  mkdirSync(deploymentsDir, { recursive: true });
  writeFileSync(join(deploymentsDir, "deployer.txt"), `${address}\n`);
  console.log(`[new-deployer] wrote deployments/deployer.txt`);
}

main();
